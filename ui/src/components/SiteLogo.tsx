import faIconsData from './faIconsData.json'

/**
 * Offline Font Awesome Free icon registry with SVG path data. Generated by
 * scripts/build-fa-icons.bat from scripts/build-fa-icons/icons.json; edit the list, not the JSON.
 */
export interface FaIconDef {
  id: string
  name: string
  /** One of the ids in FA_ICON_CATEGORIES (cms, frameworks, devtools, cloud, …). */
  category: string
  svgPath: string
  viewBox?: string
  color?: string
}

export interface FaIconCategory {
  id: string
  label: string
}

const faData = faIconsData as { categories: FaIconCategory[]; icons: FaIconDef[] }

export const FA_ICONS: FaIconDef[] = faData.icons

/** Picker filter options in display order: `all` first, then the generated categories. */
export const FA_ICON_CATEGORIES: FaIconCategory[] = [{ id: 'all', label: 'All' }, ...faData.categories]

// Lookup by id and by lower-cased name. Every rendered icon resolves through here,
// so a Map keeps a grid of hundreds of icons from doing hundreds of linear scans.
const FA_ICON_INDEX = new Map<string, FaIconDef>()
for (const icon of FA_ICONS) {
  FA_ICON_INDEX.set(icon.id, icon)
  const byName = icon.name.toLowerCase()
  if (!FA_ICON_INDEX.has(byName)) FA_ICON_INDEX.set(byName, icon)
}

/** Filters the offline catalog by picker category and search text (id or name). */
export function filterFaIcons(category: string, search: string): FaIconDef[] {
  const term = search.trim().toLowerCase()
  return FA_ICONS.filter((item) => {
    if (category !== 'all' && item.category !== category) return false
    if (!term) return true
    return item.id.includes(term) || item.name.toLowerCase().includes(term)
  })
}


/**
 * Normalizes an icon string (e.g. "fa-wordpress", "fa-brands fa-wordpress", "wordpress", "fa-globe")
 * to match against the offline catalog.
 */
export function findFaIcon(nameOrClass?: string | null): FaIconDef | undefined {
  if (!nameOrClass) return undefined
  const cleaned = nameOrClass
    .toLowerCase()
    .replace(/^fa-(solid|brands|regular|light|duotone|thin)\s+/, '')
    .replace(/^fa-/, '')
    .trim()
  return FA_ICON_INDEX.get(cleaned)
}

/**
 * Parses an icon spec that may optionally encode a custom color:
 * e.g. "rocket", "rocket|crimson", "server|#00b4d8", or "code|rgba(59, 130, 246, 0.85)".
 */
export function parseIconSpec(spec?: string | null): { name: string; color?: string } {
  if (!spec) return { name: '' }
  const idx = spec.indexOf('|')
  if (idx === -1) {
    return { name: spec.trim() }
  }
  return {
    name: spec.substring(0, idx).trim(),
    color: spec.substring(idx + 1).trim() || undefined,
  }
}

/** Formats an icon identifier and optional custom color into a persistable spec string. */
export function buildIconSpec(name: string, color?: string | null): string {
  const cleanColor = color?.trim()
  return cleanColor ? `${name.trim()}|${cleanColor}` : name.trim()
}

/** Renders an offline Font Awesome icon with crisp SVG path and custom color support (name, hex, rgba). */
export function FontAwesomeIcon({
  name,
  color,
  className = 'size-4',
  style,
  fallback = 'globe',
}: {
  name: string
  color?: string
  className?: string
  style?: React.CSSProperties
  fallback?: 'globe' | 'folder'
}) {
  const parsed = parseIconSpec(name)
  const icon = findFaIcon(parsed.name)
  if (!icon) {
    // If not found in the custom FA catalog, render the appropriate fallback icon
    return fallback === 'folder' ? (
      <DefaultFolderIcon className={className} />
    ) : (
      <DefaultInternetIcon className={className} />
    )
  }

  const activeColor = color ?? parsed.color ?? icon.color

  return (
    <svg
      viewBox={icon.viewBox ?? '0 0 512 512'}
      fill="currentColor"
      className={cn('shrink-0 select-none inline-block', className)}
      style={{ color: activeColor, ...style }}
      aria-label={icon.name}
      role="img"
    >
      <path d={icon.svgPath} />
    </svg>
  )
}

/**
 * Main SiteLogo component.
 * Priority:
 * 1. iconImage: local custom image or discovered favicon (data URL)
 *    Rendered square with border radius, subtle shadow, and object-cover.
 * 2. icon: Font Awesome icon name (offline version)
 * 3. Default: project-type icon (WordPress when detected), then globe/folder fallback
 */
export function SiteLogo({
  icon,
  iconImage,
  hostname,
  projectType,
  fallback = 'globe',
  className,
}: {
  icon?: string | null
  iconImage?: string | null
  hostname?: string
  projectType?: string | null
  fallback?: 'globe' | 'folder'
  className?: string
}) {
  if (iconImage) {
    return (
      <img
        src={iconImage}
        alt={hostname ? `Logo for ${hostname}` : 'Site logo'}
        className={cn(
          'shrink-0 select-none aspect-square rounded-md object-cover shadow-xs border border-border/60 overflow-hidden bg-muted/20',
          className || 'size-7.5',
        )}
        onError={(e) => {
          // If image fails to load or corrupted, hide and fallback handled by parent
          e.currentTarget.style.display = 'none'
        }}
      />
    )
  }

  const effectiveIcon = icon ?? projectTypeTechIcon(projectType)
  if (effectiveIcon) {
    return icon ? (
      <FontAwesomeIcon name={icon} className={cn('size-6', className)} fallback={fallback} />
    ) : (
      <TechIcon id={effectiveIcon} className={cn('size-6', className)} />
    )
  }

  if (fallback === 'folder') {
    return <DefaultFolderIcon className={cn('size-6', className)} />
  }

  return <DefaultInternetIcon className={cn('size-6', className)} />
}
