//! §166: connect Compose stacks to OLS without touching the user's compose file.
//!
//! When a stack is "connected", every OLS-run `docker compose` command adds one more file,
//! generated here into `data/docker/overrides/`. Compose merges it into each service:
//! - `extra_hosts`: every OLS site name (and `host.docker.internal`) -> this computer, so a
//!   container can call `https://shop.test` and reach OLS's own services;
//! - OLS's local CA *certificate* (public part only, copied away from its key) mounted
//!   read-only, with `NODE_EXTRA_CA_CERTS` pointing at it, so HTTPS to OLS sites is trusted.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use super::compose::{path_hash, read_file};
use crate::error::CoreError;

/// Setting: path hashes of the compose files that are connected.
pub const SETTING_CONNECTED: &str = "docker.compose.connected";
/// Where the CA certificate appears inside containers (Debian/Alpine trust-store folder).
pub const CA_IN_CONTAINER: &str = "/usr/local/share/ca-certificates/ols-local-ca.crt";

/// An OLS service and how a container reaches it.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct OlsEndpoint {
    pub id: String,
    pub name: String,
    pub running: bool,
    pub port: Option<u16>,
    /// `host.docker.internal:<port>`.
    pub address: Option<String>,
    /// The service's connection string with this computer's address swapped for
    /// `host.docker.internal`, when OLS knows one.
    pub connection: Option<String>,
}

/// What "Connect to OLS" does for one stack, shown before and after turning it on.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ConnectInfo {
    pub enabled: bool,
    /// Site names containers can reach.
    pub hostnames: Vec<String>,
    /// OLS's CA certificate exists and will be mounted.
    pub ca: bool,
    pub ca_path_in_container: String,
    pub services: Vec<OlsEndpoint>,
    /// The generated override, exactly as OLS passes it to `docker compose`.
    pub override_yaml: String,
}

/// Inputs gathered from the app (kept separate so rendering is tested without it).
#[derive(Debug, Clone, Default)]
pub struct ConnectInputs {
    pub hostnames: Vec<String>,
    /// The CA certificate copy to mount, when OLS has a CA.
    pub ca_file: Option<PathBuf>,
}

/// A host name safe to write into `extra_hosts`.
fn valid_hostname(h: &str) -> bool {
    !h.is_empty()
        && h.len() <= 253
        && h.contains('.')
        && h.split('.').all(|l| {
            !l.is_empty()
                && l.len() <= 63
                && l.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
        })
}

fn q(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The override for these services. Deterministic: same inputs, same text.
pub fn render_override(services: &[String], inputs: &ConnectInputs) -> String {
    let hosts: BTreeSet<String> = inputs
        .hostnames
        .iter()
        .map(|h| h.trim().to_lowercase())
        .filter(|h| valid_hostname(h))
        .collect();
    let mut out = String::from(
        "# Generated by Open Local Server for \"Connect to OLS\". Do not edit: it is rewritten on every run.\n",
    );
    if services.is_empty() {
        out.push_str("services: {}\n");
        return out;
    }
    out.push_str("services:\n");
    for svc in services {
        out.push_str(&format!("  {}:\n    extra_hosts:\n", q(svc)));
        out.push_str("      - \"host.docker.internal:host-gateway\"\n");
        for h in &hosts {
            out.push_str(&format!("      - {}\n", q(&format!("{h}:host-gateway"))));
        }
        if let Some(ca) = &inputs.ca_file {
            out.push_str("    volumes:\n");
            out.push_str(&format!(
                "      - type: bind\n        source: {}\n        target: {}\n        read_only: true\n",
                q(&ca.display().to_string()),
                q(CA_IN_CONTAINER)
            ));
            out.push_str("    environment:\n");
            out.push_str(&format!(
                "      NODE_EXTRA_CA_CERTS: {}\n",
                q(CA_IN_CONTAINER)
            ));
            out.push_str(&format!("      OLS_CA_CERT: {}\n", q(CA_IN_CONTAINER)));
        }
    }
    out
}

/// Service names in a compose file.
pub fn service_names(text: &str) -> Vec<String> {
    serde_yaml_ng::from_str::<serde_yaml_ng::Value>(text)
        .ok()
        .and_then(|d| d.get("services").and_then(|s| s.as_mapping()).cloned())
        .map(|m| {
            m.keys()
                .filter_map(|k| k.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

pub fn override_path(data_dir: &Path, file: &Path) -> PathBuf {
    data_dir
        .join("docker")
        .join("overrides")
        .join(format!("{}.yaml", path_hash(file)))
}

/// Copies the CA certificate (never the key) next to the overrides, so the folder Docker
/// is given holds nothing else. `None` when OLS has no CA yet.
pub fn stage_ca(data_dir: &Path, ca_cert: &Path) -> Option<PathBuf> {
    if !ca_cert.is_file() {
        return None;
    }
    let dest = data_dir.join("docker").join("ols-local-ca.crt");
    std::fs::create_dir_all(dest.parent()?).ok()?;
    let pem = std::fs::read(ca_cert).ok()?;
    // Only a certificate may be shared; refuse anything that looks like a key.
    let text = String::from_utf8_lossy(&pem);
    if !text.contains("BEGIN CERTIFICATE") || text.contains("PRIVATE KEY") {
        return None;
    }
    if std::fs::read(&dest).ok().as_deref() != Some(pem.as_slice()) {
        std::fs::write(&dest, &pem).ok()?;
    }
    Some(dest)
}

/// Writes the override for a compose file and returns its path.
pub fn write_override(
    data_dir: &Path,
    file: &Path,
    text: &str,
    inputs: &ConnectInputs,
) -> Result<PathBuf, CoreError> {
    let path = override_path(data_dir, file);
    let yaml = render_override(&service_names(text), inputs);
    std::fs::create_dir_all(path.parent().expect("has parent"))
        .and_then(|_| std::fs::write(&path, yaml))
        .map_err(|e| {
            CoreError::failed_fix(
                "OLS could not prepare the connection to OLS for this stack.",
                format!("Writing {}: {e}", path.display()),
                "Check that OLS's data folder is writable, or turn off Connect to OLS for this stack.",
            )
        })?;
    Ok(path)
}

/// Rewrites `127.0.0.1` / `localhost` in a connection string to `host.docker.internal`.
pub fn for_container(connection: &str) -> String {
    connection
        .replace("127.0.0.1", "host.docker.internal")
        .replace("localhost", "host.docker.internal")
}

/// The connection preview for a file (reads it to know its services).
pub fn info(
    path: &str,
    enabled: bool,
    inputs: &ConnectInputs,
    services: Vec<OlsEndpoint>,
) -> Result<ConnectInfo, CoreError> {
    let text = read_file(path)?;
    let mut hostnames: Vec<String> = inputs
        .hostnames
        .iter()
        .map(|h| h.trim().to_lowercase())
        .filter(|h| valid_hostname(h))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    hostnames.sort();
    Ok(ConnectInfo {
        enabled,
        ca: inputs.ca_file.is_some(),
        ca_path_in_container: CA_IN_CONTAINER.into(),
        override_yaml: render_override(&service_names(&text), inputs),
        hostnames,
        services,
    })
}

impl crate::app::Inner {
    /// Path hashes of connected compose files.
    pub fn docker_connected(&self) -> BTreeSet<String> {
        self.settings
            .lock()
            .unwrap()
            .get(SETTING_CONNECTED)
            .and_then(|v| v.as_array().cloned())
            .unwrap_or_default()
            .into_iter()
            .filter_map(|v| v.as_str().map(str::to_string))
            .collect()
    }

    pub fn docker_is_connected(&self, file: &Path) -> bool {
        self.docker_connected().contains(&path_hash(file))
    }

    pub fn set_docker_connected(&self, file: &Path, on: bool) -> Result<(), CoreError> {
        let mut set = self.docker_connected();
        let h = path_hash(file);
        if on {
            set.insert(h);
        } else {
            set.remove(&h);
        }
        let value =
            serde_json::Value::Array(set.into_iter().map(serde_json::Value::String).collect());
        self.settings.lock().unwrap().set(SETTING_CONNECTED, value)
    }

    /// Current site names (enabled sites and their aliases) and the staged CA certificate.
    pub fn docker_connect_inputs(&self) -> ConnectInputs {
        let domains = self.domains.lock().unwrap().list();
        let hostnames = domains
            .iter()
            .filter(|d| d.enabled)
            .flat_map(|d| std::iter::once(d.hostname.clone()).chain(d.aliases.iter().cloned()))
            .collect();
        let ca = crate::ca::LocalCa::new(&self.paths).ca_cert_pem_path();
        ConnectInputs {
            hostnames,
            ca_file: stage_ca(&self.paths.data_dir(), &ca),
        }
    }

    /// The connection for a run of this file, or `None` when it is not connected.
    pub fn docker_connect_for(&self, file: &Path) -> Option<super::compose::Connect> {
        self.docker_is_connected(file)
            .then(|| super::compose::Connect {
                data_dir: self.paths.data_dir(),
                inputs: self.docker_connect_inputs(),
            })
    }

    /// OLS services (not web servers: containers reach sites by name) and how a container
    /// reaches each one.
    pub fn docker_ols_endpoints(&self) -> Vec<OlsEndpoint> {
        self.services
            .list()
            .into_iter()
            .filter(|s| s.kind != "web" && s.installed)
            .map(|s| OlsEndpoint {
                address: s.port.map(|p| format!("host.docker.internal:{p}")),
                connection: s.connection.as_deref().map(for_container),
                id: s.id,
                name: s.name,
                running: s.running,
                port: s.port,
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn override_adds_sites_and_ca_to_every_service() {
        let inputs = ConnectInputs {
            hostnames: vec![
                "Shop.test".into(),
                "blog.test".into(),
                "*.bad".into(),
                "nodot".into(),
                "shop.test".into(),
            ],
            ca_file: Some(PathBuf::from("C:\\OLS\\data\\docker\\ols-local-ca.crt")),
        };
        let yaml = render_override(&["web".into(), "db".into()], &inputs);
        let doc: serde_yaml_ng::Value = serde_yaml_ng::from_str(&yaml).expect("valid YAML");
        for svc in ["web", "db"] {
            let s = doc.get("services").unwrap().get(svc).unwrap();
            let hosts: Vec<&str> = s
                .get("extra_hosts")
                .unwrap()
                .as_sequence()
                .unwrap()
                .iter()
                .map(|v| v.as_str().unwrap())
                .collect();
            assert_eq!(
                hosts,
                vec![
                    "host.docker.internal:host-gateway",
                    "blog.test:host-gateway",
                    "shop.test:host-gateway"
                ]
            );
            let vol = &s.get("volumes").unwrap().as_sequence().unwrap()[0];
            assert_eq!(
                vol.get("source").unwrap().as_str(),
                Some("C:\\OLS\\data\\docker\\ols-local-ca.crt")
            );
            assert_eq!(vol.get("target").unwrap().as_str(), Some(CA_IN_CONTAINER));
            assert_eq!(vol.get("read_only").unwrap().as_bool(), Some(true));
            assert_eq!(
                s.get("environment")
                    .unwrap()
                    .get("NODE_EXTRA_CA_CERTS")
                    .unwrap()
                    .as_str(),
                Some(CA_IN_CONTAINER)
            );
        }
        // Without a CA only the host names are added.
        let plain = render_override(
            &["web".into()],
            &ConnectInputs {
                hostnames: vec![],
                ca_file: None,
            },
        );
        assert!(!plain.contains("volumes") && plain.contains("host-gateway"));
    }

    #[test]
    fn only_the_certificate_is_ever_staged() {
        let tmp = tempfile::tempdir().unwrap();
        let cert = tmp.path().join("ca.pem");
        std::fs::write(
            &cert,
            "-----BEGIN CERTIFICATE-----\nabc\n-----END CERTIFICATE-----\n",
        )
        .unwrap();
        let staged = stage_ca(tmp.path(), &cert).expect("staged");
        assert!(staged.ends_with("ols-local-ca.crt"));
        let key = tmp.path().join("ca-key.pem");
        std::fs::write(
            &key,
            "-----BEGIN PRIVATE KEY-----\nabc\n-----END PRIVATE KEY-----\n",
        )
        .unwrap();
        assert!(
            stage_ca(tmp.path(), &key).is_none(),
            "a key is never shared"
        );
        assert!(stage_ca(tmp.path(), &tmp.path().join("missing.pem")).is_none());
    }

    #[test]
    fn connection_strings_point_at_the_host() {
        assert_eq!(
            for_container("mysql://root@127.0.0.1:3306"),
            "mysql://root@host.docker.internal:3306"
        );
        assert_eq!(
            for_container("redis://localhost:6379"),
            "redis://host.docker.internal:6379"
        );
    }

    #[test]
    fn override_and_file_merge_in_compose_order() {
        let tmp = tempfile::tempdir().unwrap();
        let file = tmp.path().join("compose.yaml");
        std::fs::write(&file, "services:\n  web:\n    image: nginx:1.28\n").unwrap();
        let p = write_override(
            tmp.path(),
            &file,
            &std::fs::read_to_string(&file).unwrap(),
            &ConnectInputs::default(),
        )
        .unwrap();
        assert!(p.starts_with(tmp.path().join("docker").join("overrides")));
        assert!(std::fs::read_to_string(&p).unwrap().contains("\"web\":"));
    }
}
