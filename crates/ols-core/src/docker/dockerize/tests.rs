#[test]
fn laravel_gets_services_workers_and_assets() {
    let d = dir();
    put(d.path(), "composer.json", r#"{"require":{"php":"^8.3"}}"#);
    put(d.path(), "artisan", "");
    put(d.path(), "routes/console.php", "<?php");
    put(
        d.path(),
        ".env.example",
        "DB_CONNECTION=mysql\nQUEUE_CONNECTION=redis\nCACHE_STORE=redis\nMAIL_MAILER=smtp\n",
    );
    put(
        d.path(),
        "package.json",
        r#"{"scripts":{"build":"vite build"},"devDependencies":{"vite":"6","laravel-vite-plugin":"1"}}"#,
    );
    let p = make(d.path());
    let ids: Vec<&str> = p
        .services
        .iter()
        .filter(|s| s.selected)
        .map(|s| s.id.as_str())
        .collect();
    assert_eq!(ids, vec!["mariadb", "redis", "mailpit"]);
    assert!(p.compose.contains("DB_HOST: \"db\""));
    assert!(p.compose.contains("DB_CONNECTION: \"mysql\""));
    assert!(p.compose.contains("REDIS_HOST: \"redis\""));
    assert!(p.compose.contains("MAIL_HOST: \"mail\""));
    assert!(p.compose.contains("condition: service_healthy"));
    assert!(p.compose.contains("healthcheck.sh"));
    // Passwords are variables, never values.
    assert!(p.compose.contains("${OLS_SECRET_DB_MARIADB_PASSWORD:?"));
    assert!(p
        .secrets
        .contains(&"OLS_SECRET_DB_MARIADB_PASSWORD".to_string()));
    assert!(p
        .secrets
        .contains(&"OLS_SECRET_DB_MARIADB_ROOT_PASSWORD".to_string()));
    // Workers reuse the app image.
    assert_eq!(p.workers.len(), 2);
    assert!(p.compose.contains("queue:work"));
    assert!(p.compose.contains("schedule:work"));
    assert!(p.compose.contains("pull_policy: never"));
    assert!(compose::check_text(&p.compose).ok);
    // Dev: the database is reachable from the host on a free port.
    assert!(p.compose.contains("127.0.0.1:3307:3306"));
    // Production: Vite assets are built in a Node stage; no host ports for services.
    let p = prod(d.path());
    let df = p.dockerfile.unwrap();
    assert!(df.contains("AS assets"));
    assert!(df.contains("COPY --from=assets"));
    assert!(!p.compose.contains("127.0.0.1:3307"));
    assert!(!p.services.iter().any(|s| s.id == "mailpit" && s.selected));
}

