use super::*;

fn dir() -> tempfile::TempDir {
    tempfile::tempdir().unwrap()
}
fn put(d: &Path, name: &str, text: &str) {
    if let Some(parent) = Path::new(name).parent() {
        std::fs::create_dir_all(d.join(parent)).unwrap();
    }
    std::fs::write(d.join(name), text).unwrap();
}
fn free(_: u16) -> bool {
    true
}
fn make(d: &Path) -> DockerizePlan {
    plan(d, None, &free, &DockerizeOptions::default()).unwrap()
}
fn make_with(d: &Path, mode: DockerizeMode, services: Option<Vec<&str>>) -> DockerizePlan {
    let options = DockerizeOptions {
        mode,
        services: services.map(|s| s.into_iter().map(String::from).collect()),
    };
    plan(d, None, &free, &options).unwrap()
}
fn prod(d: &Path) -> DockerizePlan {
    make_with(d, DockerizeMode::Prod, None)
}
fn sample(kind: &str) -> tempfile::TempDir {
    let d = dir();
    match kind {
        "node" => put(d.path(), "package.json", r#"{"scripts":{"dev":"vite"}}"#),
        "php" => put(d.path(), "composer.json", r#"{"require":{"php":"^8.2"}}"#),
        "python" => {
            put(d.path(), "requirements.txt", "django\n");
            put(d.path(), "manage.py", "");
        }
        "go" => put(d.path(), "go.mod", "module x\n\ngo 1.23\n"),
        "rust" => put(d.path(), "Cargo.toml", "[package]\nname = \"demo\"\n"),
        "ruby" => put(d.path(), "Gemfile", "source 'https://rubygems.org'\n"),
        "java" => put(
            d.path(),
            "pom.xml",
            "<project><properties><java.version>17</java.version></properties></project>",
        ),
        "dotnet" => put(
            d.path(),
            "Web.csproj",
            "<Project><PropertyGroup><TargetFramework>net9.0</TargetFramework></PropertyGroup></Project>",
        ),
        _ => put(d.path(), "index.html", "<html></html>"),
    }
    d
}
const KINDS: [&str; 9] = [
    "node", "php", "python", "static", "go", "rust", "ruby", "java", "dotnet",
];

#[test]
fn every_kind_carries_the_fixed_honesty_block_in_both_modes() {
    for kind in KINDS {
        for mode in [DockerizeMode::Dev, DockerizeMode::Prod] {
            let d = sample(kind);
            let p = make_with(d.path(), mode, None);
            assert_eq!(p.kind, kind);
            assert_eq!(p.mode, mode);
            assert_eq!(p.disclaimer, DISCLAIMER);
            assert_eq!(p.checklist, CHECKLIST.to_vec());
            assert!(!p.detected.is_empty());
            for text in [p.dockerfile.as_ref().unwrap(), &p.compose] {
                let first: Vec<&str> = text.lines().take(3).collect();
                assert!(
                    first.iter().all(|l| l.starts_with('#')),
                    "{kind}: {first:?}"
                );
                assert!(first[0].starts_with("# Generated by Open Local Server"));
                assert!(first[2].starts_with("# Detected: "));
            }
            assert!(compose::check_text(&p.compose).ok, "{kind}");
            assert!(
                p.compose.contains(":local\""),
                "{kind}: the built image is named"
            );
            assert!(!p.compose.contains(":latest"), "{kind}");
            assert!(p.dockerfile.as_ref().unwrap().contains("\nFROM "), "{kind}");
            assert!(p.dockerignore.as_ref().unwrap().contains(".env"), "{kind}");
        }
    }
}

