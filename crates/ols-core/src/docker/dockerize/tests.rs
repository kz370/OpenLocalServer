#[test]
fn write_creates_the_files_once_and_stores_each_secret_once() {
    let d = sample("php");
    put(d.path(), ".env.example", "DB_CONNECTION=mysql\n");
    let p = make(d.path());
    assert!(!p.secrets.is_empty());
    let stored = std::cell::RefCell::new(Vec::new());
    write(&p, false, &d.path().join("b"), &|_| false, &|k, v| {
        assert!(!v.is_empty());
        stored.borrow_mut().push(k.to_string());
        Ok(())
    })
    .unwrap();
    assert_eq!(stored.borrow().len(), p.secrets.len());
    assert!(d.path().join("Dockerfile").is_file());
    assert!(d.path().join("compose.yaml").is_file());
    assert!(d.path().join(".dockerignore").is_file());
    assert!(write(&p, false, &d.path().join("b"), &|_| false, &|_, _| Ok(())).is_err());
    // A password that already exists is kept.
    let e = dir();
    put(e.path(), "composer.json", "{}");
    put(e.path(), ".env.example", "DB_CONNECTION=mysql\n");
    let p = make(e.path());
    write(&p, false, &e.path().join("b"), &|_| true, &|_, _| {
        panic!("must not store")
    })
    .unwrap();
}

